// Shared by the homepage and the generated /people/<slug>/ pages.
// Renders Instagram / X posts as lazy iframes, sized via the platforms' own postMessage reports.

function el(tag, attrs = {}, text) {
  const n = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) n.setAttribute(k, v);
  if (text != null) n.textContent = text;
  return n;
}

// Broad to narrow, on one line: "United States, Utah, Salt Lake City"
const fullPlace = (p) => [p.country, p.region, p.city].filter(Boolean).join(", ") || "Location unspecified";

// Which platform a post_url points at, plus the ID we need to embed it.
function source(url = "") {
  let m = url.match(/instagram\.com\/(?:p|reel)\/([A-Za-z0-9_-]+)/);
  if (m) return { kind: "ig", code: m[1] };
  m = url.match(/(?:x|twitter)\.com\/[^/]+\/status\/(\d+)/);
  if (m) return { kind: "x", id: m[1] };
  return null;
}

// Both platforms encode the post time in the ID itself.
// Instagram: shortcode -> media ID, top bits = ms since 2011-08-24. X: snowflake, top bits = ms since 2010-11-04.
const IG_ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
function postedAt(p) {
  if (p.posted) return new Date(p.posted);
  const s = source(p.post_url);
  if (s?.kind === "ig") {
    let id = 0n;
    for (const ch of s.code.slice(0, 11)) id = id * 64n + BigInt(IG_ALPHABET.indexOf(ch));
    return new Date(Number(id >> 23n) + 1314220021721);
  }
  if (s?.kind === "x") return new Date(Number(BigInt(s.id) >> 22n) + 1288834974657);
  return null;
}
const fmtDate = (d) => d.toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric" });

// Profiles with a bio get their own page (generated by build.py).
const slugOf = (p) => p.slug || p.id;
const personUrl = (p) => (p.bio ? `/people/${slugOf(p)}/` : null);

// Embeds are plain iframes with loading="lazy": nothing from Instagram or X loads until a
// card is about to scroll into view, and no embed.js / widgets.js scripts are needed at all.
const dark = matchMedia("(prefers-color-scheme: dark)").matches;
function frameSrc(s) {
  return s.kind === "ig"
    ? `https://www.instagram.com/p/${s.code}/embed/captioned/`
    : `https://platform.twitter.com/embed/Tweet.html?id=${s.id}&dnt=true&theme=${dark ? "dark" : "light"}`;
}

function embedFrame(postUrl) {
  const s = source(postUrl);
  const frame = el("div", { class: `frame ${s.kind}` });
  frame.append(el("a", { class: "fallback", href: postUrl, target: "_blank", rel: "noopener" },
    s.kind === "ig" ? "View on Instagram →" : "View on X →"));
  const f = el("iframe", {
    src: frameSrc(s), loading: "lazy", title: s.kind === "ig" ? "Instagram post" : "Post on X",
    scrolling: "no", referrerpolicy: "strict-origin-when-cross-origin",
  });
  // X sometimes never sends its size on the first load; reload the frame once if so.
  let retried = false;
  f.addEventListener("load", () => setTimeout(() => {
    if (!frame.classList.contains("ready") && !retried) { retried = true; f.src = f.src; }
  }, 5000));
  frame.append(f);
  return frame;
}

// Turn static <div data-post-url="..."> placeholders into live embeds (used on people pages).
function upgradeEmbeds(root = document) {
  for (const n of root.querySelectorAll("[data-post-url]")) {
    if (source(n.dataset.postUrl)) n.replaceWith(embedFrame(n.dataset.postUrl));
  }
}

// Both embeds report their real height via postMessage; size each iframe to fit.
addEventListener("message", (e) => {
  let host;
  try { host = new URL(e.origin).hostname; } catch { return; }
  if (!/(^|\.)instagram\.com$|^platform\.twitter\.com$/.test(host)) return;
  let msg = e.data, h;
  try { if (typeof msg === "string") msg = JSON.parse(msg); } catch { return; }
  if (msg?.type === "MEASURE") h = msg.details?.height;
  const x = msg?.["twttr.embed"];
  if (x?.method === "twttr.private.resize") h = x.params?.[0]?.height;
  if (!h) return;
  for (const f of document.querySelectorAll(".frame iframe")) {
    if (f.contentWindow === e.source) { f.style.height = `${Math.ceil(h)}px`; f.parentElement.classList.add("ready"); }
  }
});

#!/usr/bin/env python3
"""Generate /people/<slug>/index.html for every profile in profiles.json that has a "bio".

Run after editing profiles.json, then commit the result:

    python3 build.py

Pages are plain static HTML (good for sharing and search engines); the embedded post is
upgraded to a live Instagram / X embed by /embeds.js. Pages for profiles that no longer
have a bio (or were removed) are deleted.
"""
import html
import json
import re
import shutil
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PEOPLE = ROOT / "people"
MARKER = "<!-- generated by build.py -->"
IG_ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"


def slug_of(p):
    return p.get("slug") or p["id"]


def full_place(p):
    return ", ".join(x for x in (p.get("country"), p.get("region"), p.get("city")) if x) or "Location unspecified"


def posted_at(p):
    """Same decoding as postedAt() in embeds.js."""
    if p.get("posted"):
        return datetime.fromisoformat(p["posted"])
    url = p.get("post_url", "")
    m = re.search(r"instagram\.com/(?:p|reel)/([A-Za-z0-9_-]+)", url)
    if m:
        n = 0
        for ch in m.group(1)[:11]:
            n = n * 64 + IG_ALPHABET.index(ch)
        return datetime.fromtimestamp(((n >> 23) + 1314220021721) / 1000, timezone.utc)
    m = re.search(r"(?:x|twitter)\.com/[^/]+/status/(\d+)", url)
    if m:
        return datetime.fromtimestamp(((int(m.group(1)) >> 22) + 1288834974657) / 1000, timezone.utc)
    return None


def render_bio(text):
    """Blank lines split paragraphs; bare URLs become links. Everything else is escaped."""
    paras = [x.strip() for x in re.split(r"\n\s*\n", text.strip()) if x.strip()]
    out = []
    for para in paras:
        parts = re.split(r"(https?://\S+)", para)
        h = ""
        for i, part in enumerate(parts):
            if i % 2:
                url = part.rstrip(".,;:!?)")
                tail = part[len(url):]
                h += f'<a href="{html.escape(url)}" target="_blank" rel="noopener">{html.escape(url)}</a>{html.escape(tail)}'
            else:
                h += html.escape(part).replace("\n", "<br>")
        out.append(f"<p>{h}</p>")
    return "\n        ".join(out)


def page(p):
    name = p.get("name") or (p.get("instagram") or p.get("x") or slug_of(p))
    place = full_place(p)
    d = posted_at(p)
    date = " · ".join(x for x in (
        f"Posted {d.day} {d.strftime('%b %Y')}" if d else "",
        "Relocation friendly" if p.get("relocation") else "",
    ) if x)
    first_line = re.sub(r"https?://\S+", "", p["bio"]).strip().split("\n")[0][:155]
    e = html.escape
    return f"""<!DOCTYPE html>
{MARKER}
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{e(name)} · DatingRelating.com</title>
  <meta name="description" content="{e(first_line)}">
  <meta property="og:title" content="{e(name)} · DatingRelating.com">
  <meta property="og:description" content="{e(first_line)}">
  <link rel="canonical" href="https://datingrelating.com/people/{e(slug_of(p))}/">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Instrument+Serif:ital@0;1&family=Inter:wght@400;500;600&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="/style.css">
  <style>
    .person {{ display: grid; grid-template-columns: minmax(0, 1fr) 400px; gap: 48px; align-items: start; padding: 40px 0 0; }}
    @media (max-width: 860px) {{ .person {{ grid-template-columns: 1fr; gap: 28px; }} }}
    .back {{ color: var(--muted); text-decoration: none; font-size: 14px; }}
    .back:hover {{ color: var(--text); }}
    .person h1 {{ font-size: clamp(44px, 7vw, 84px); margin-top: 16px; }}
    .where {{ font-family: "Instrument Serif", Georgia, serif; font-size: 26px; margin: 18px 0 2px; }}
    .when {{ color: var(--muted); font-size: 14px; margin: 0; }}
    .bio {{ margin-top: 28px; padding: 24px 26px; }}
    .bio p {{ font-size: 18px; margin: 0 0 12px; }}
    .bio p:last-child {{ margin-bottom: 0; }}
    .bio a {{ color: var(--accent); word-break: break-word; }}
    .post {{ padding: 14px; }}
  </style>
</head>
<body>
  <div class="blobs" aria-hidden="true"><span></span><span></span><span></span></div>

  <div class="wrap">
    <nav>
      <a class="logo" href="/">Dating<b>Relating</b></a>
      <div class="navlinks">
        <a href="/" aria-current="page">Dating</a>
        <a href="/relating/">Relating</a>
        <a href="/hacker-mindset/">Hacker Mindset</a>
        <a href="/co-founder-co-lover/">Co-founder &amp; Co-lover</a>
        <a href="/about/">About</a>
      </div>
    </nav>

    <section class="person">
      <div>
        <a class="back" href="/">← Everyone</a>
        <h1>{e(name)}</h1>
        <p class="where">{e(place)}</p>
        <p class="when">{e(date)}</p>
        <div class="panel bio">
        {render_bio(p["bio"])}
        </div>
      </div>
      <div class="panel post">
        <div data-post-url="{e(p.get("post_url", ""))}">
          <a class="fallback" href="{e(p.get("post_url", ""))}" target="_blank" rel="noopener">View the original post →</a>
        </div>
      </div>
    </section>

    <section class="join">
      <h2>Want your own page?</h2>
      <p>Send your post, where you are, and what you would like people to know.</p>
      <div class="row">
        <a class="btn" href="mailto:datingrelatingdotcom@gmail.com">Email us</a>
        <a class="btn ghost" href="/">Back to everyone</a>
      </div>
    </section>

    <p class="fine">
      Listed and want to be taken down, or moved city?
      <a href="mailto:datingrelatingdotcom@gmail.com">Email us</a> and it is done the same day.
    </p>
  </div>

  <script src="/embeds.js"></script>
  <script>upgradeEmbeds();</script>
</body>
</html>
"""


def main():
    profiles = json.loads((ROOT / "profiles.json").read_text())
    wanted = {slug_of(p): p for p in profiles if p.get("bio")}

    # Remove pages this script made earlier that are no longer wanted.
    if PEOPLE.exists():
        for d in PEOPLE.iterdir():
            f = d / "index.html"
            if d.is_dir() and d.name not in wanted and f.exists() and MARKER in f.read_text():
                shutil.rmtree(d)
                print(f"removed  people/{d.name}/")

    for slug, p in wanted.items():
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", slug):
            raise SystemExit(f"Bad slug {slug!r}: use lowercase letters, digits and dashes")
        out = PEOPLE / slug / "index.html"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(page(p))
        print(f"wrote    people/{slug}/")


if __name__ == "__main__":
    main()
